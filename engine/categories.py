def denied(name):
    n = (name or "").lower()
    return any(d in n for d in DENY)

def assign_category(name, niche=None):
    """Категория по названию; ниша задаёт значение по умолчанию."""
    n = (name or "").lower()
    tokens = set(n.replace("-", " ").replace(".", " ").split())
    # банки: токен, оканчивающийся на «банк», или известные паттерны
    if any(t.endswith("банк") for t in tokens) or "monobank" in n or "монобанк" in n:
        return 13
    if any(k in n for k in ["крипт", "crypto", "форекс", "forex", "брокер", "бирж", "обменник", "трейд", "trading"]):
        return 48
    if any(k in n for k in ["кредит", "займ", "заём", "мікропозик", "микрозайм", "ломбард", "гроші", "гроши"]):
        return 50
    if any(k in n for k in ["курс", "школ", "академ", "academy", "school", "навчання", "освіт"]):
        return 83
    if any(k in n for k in ["трудоустрой", "робота за кордоном", "работа за границей"]):
        return 42
    if any(k in n for k in ["інтернет-магазин", "интернет-магазин", "магазин", "shop", "store"]):
        return 45
    if niche and niche in NICHES:
        return NICHES[niche]["term_id"]
    return 18
